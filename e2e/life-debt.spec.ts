import {test,expect} from '@playwright/test';
import {loadContent} from '../scripts/load-content.mjs';
import {createGameSave,encodeGameSave} from '../src/core/game-save.js';
import {beginChronicleEvent} from '../src/core/chronicles.js';
import {createChronicleBattle,snapshotChronicleBattle} from '../src/core/chronicle-combat.js';
const content:any=await loadContent();
test('Thế Chấp shows a separate debt bar and exact HP tooltip on desktop and mobile',async({page})=>{
 let save=beginChronicleEvent(createGameSave(content),content,'a',{random:()=>.5});
 const pending=save.chronicles.pendingByLocation.a;
 save.chronicles.firstClearIds=[content.chronicles.book1.locations.find((l:any)=>l.id==='a').introId];
 pending.eventId='book1.a03';pending.battleStepId=content.chronicleEvents['book1.a03'].steps.find((s:any)=>s.battle).id;
 pending.stepId=pending.battleStepId;pending.status='battle';
 const battle=createChronicleBattle(content,save,'a',pending.instanceId);
 const arthur=battle.actors.find((a:any)=>a.characterId==='arthur'||a.id==='arthur');
 arthur.statuses.push({id:'life_mortgage',remaining:null,stacks:1,sourceId:battle.actors.find((a:any)=>a.team==='enemy').id,debtHp:40});
 pending.battleSnapshot=snapshotChronicleBattle(battle);save.chronicles.activeBattle='a';
 await page.addInitScript(raw=>{localStorage.setItem('northern-prisma.campaign.v7',raw);sessionStorage.setItem('northern-prisma.entered','1');localStorage.setItem('northern-prisma.settings.v1',JSON.stringify({musicEnabled:false,controlMode:'mouse'}));},encodeGameSave(save,content));
 await page.emulateMedia({reducedMotion:'reduce'});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/battle');
 const card=page.locator(`[data-actor-id="${arthur.id}"]`);
 await expect(card.locator('.life-debt-meter')).toHaveText('Thế Chấp: 40 HP');
 await expect(card.getByRole('progressbar',{name:'Sinh Mệnh Thế Chấp'})).toHaveAttribute('value','40');
 await card.getByRole('button',{name:'Xem hiệu ứng Sinh Mệnh Thế Chấp'}).hover();
 await expect(page.getByText('Còn 40 HP Thế Chấp cần thanh toán. Thanh toán không kích hiệu ứng được hồi HP.',{exact:true})).toBeVisible();
 await page.keyboard.press('Escape');
 await page.locator('h1').click();
 await page.mouse.move(0,0);
 await page.screenshot({path:'test-results/life-debt-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await expect(card.locator('.life-debt-meter')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.screenshot({path:'test-results/life-debt-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});
