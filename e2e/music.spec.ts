import { test, expect } from '@playwright/test';

test('tavern MP3 plays on home with shared controls and independent battle playback', async ({ page, request }) => {
  const response = await request.get('/bgm/tavern.mp3', { headers: { Range: 'bytes=0-127' } });
  expect(response.status()).toBe(206); expect((await response.body()).length).toBe(128);
  const shopResponse = await request.get('/bgm/shop.mp3', { headers: { Range: 'bytes=0-127' } });
  expect(shopResponse.status()).toBe(206); expect((await shopResponse.body()).length).toBe(128);
  await page.addInitScript(() => {
    const create = document.createElement.bind(document);
    (window as any).__music = [];
    document.createElement = function(...args: any[]) {
      const element = (create as any)(...args);
      if (args[0] === 'audio') (window as any).__music.push(element);
      return element;
    } as typeof document.createElement;
  });
  await page.goto('/');
  await page.getByRole('button',{name:'Tạo hành trình mới'}).click();
  await page.getByLabel('Tên người chơi',{exact:true}).fill('Arthur');
  await page.getByRole('button',{name:'Lưu',exact:true}).click();
  await expect(page).toHaveURL(/\/home$/);
  const audio = () => page.evaluate(() => (window as any).__music.map((item: HTMLAudioElement) => ({ src: item.src, paused: item.paused, time: item.currentTime, volume: item.volume, loop: item.loop })));
  await expect.poll(async () => (await audio())[1]?.src).toContain('/bgm/tavern.mp3');
  await expect.poll(async () => (await audio())[1]?.paused).toBe(false);
  await page.getByRole('button', { name: 'Mở Settings' }).click();
  await page.locator('.volume').fill('0.6');
  await expect.poll(async () => (await audio()).every((item: any) => item.volume === .6)).toBe(true);
  await page.locator('.audio-toggle').click();
  await expect.poll(async () => (await audio())[1].paused).toBe(true);
  await page.locator('.audio-toggle').click();
  await expect.poll(async () => (await audio())[1].time).toBeGreaterThan(.1);
  await page.getByRole('button', { name: 'Đóng Settings' }).click();
  await page.getByRole('link', { name: /Đội Hình/ }).click();
  await expect.poll(async () => (await audio())[1].paused).toBe(true);
  const paused = (await audio())[1];
  await page.getByRole('link', { name: /NORTHERN PRISMA/ }).click();
  await expect.poll(async () => (await audio())[1].paused).toBe(false);
  expect((await audio())[1].time).toBeGreaterThanOrEqual(paused.time);
  await page.locator('.header-shop').click();
  await expect.poll(async () => (await audio())[2]?.src).toContain('/bgm/shop.mp3');
  await expect.poll(async () => (await audio())[2]?.paused).toBe(false);
  expect((await audio())[2].loop).toBe(true);
  await expect.poll(async () => (await audio())[1].paused).toBe(true);
  await expect.poll(async () => (await audio())[2].time).toBeGreaterThan(.1);
  const shopTime = (await audio())[2].time;
  await page.locator('.shop-tabs a').nth(1).click();
  await expect(page).toHaveURL(/shop\?tab=recruitment$/);
  expect((await audio())[2].time).toBeGreaterThanOrEqual(shopTime);
  await page.getByRole('button', { name: 'Mở Settings' }).click();
  await page.locator('.audio-toggle').click();
  await expect.poll(async () => (await audio())[2].paused).toBe(true);
  await page.locator('.audio-toggle').click();
  await expect.poll(async () => (await audio())[2].paused).toBe(false);
  await page.getByRole('button', { name: 'Đóng Settings' }).click();
  await page.getByRole('link', { name: /NORTHERN PRISMA/ }).click();
  await expect.poll(async () => (await audio())[2].paused).toBe(true);
  await expect.poll(async () => (await audio())[1].paused).toBe(false);
  await page.goto('/quests');
  await page.getByRole('button', { name: /Xuất chiến/ }).click();
  await expect(page).toHaveURL(/\/battle$/);
  await expect.poll(async () => (await audio())[0].paused).toBe(false);
  expect((await audio())[1].paused).toBe(true);
  await page.getByRole('link', { name: /NORTHERN PRISMA/ }).click();
  await expect.poll(async () => (await audio())[1].paused).toBe(false);
  expect((await audio())[0].paused).toBe(true);
});
